import type { SpecEntry, Size } from './types.js';

// Sources (checked 2026-11-18, see .claude/research/2026-11-18_store-media-specs.md section C).
const LISTING = 'https://support.google.com/googleplay/android-developer/answer/9866151';
const ICON = 'https://developer.android.com/distribute/google-play/resources/icon-design-specifications';
const ADAPTIVE = 'https://developer.android.com/develop/ui/views/launch/icon_design_adaptive';
const DENSITIES = 'https://developer.android.com/training/multiscreen/screendensities';
const TV = 'https://developer.android.com/training/tv/start/start';

const KB = 1024;
const MB = 1024 * KB;
const squares = (...sides: number[]): Size[] => sides.map((side) => ({ width: side, height: side }));

/** Pixel sizes of a 108 dp adaptive icon layer at mdpi, hdpi, xhdpi, xxhdpi and xxxhdpi. */
export const ADAPTIVE_LAYER_SIDES = [108, 162, 216, 324, 432] as const;
/** Pixel sizes of a 48 dp legacy launcher icon at mdpi, hdpi, xhdpi, xxhdpi and xxxhdpi. */
export const LEGACY_LAUNCHER_SIDES = [48, 72, 96, 144, 192] as const;
/** Android density qualifiers, in the order of the two size lists above. */
export const ANDROID_DENSITIES = ['mdpi', 'hdpi', 'xhdpi', 'xxhdpi', 'xxxhdpi'] as const;
/** Output folder of all Android launcher resources (copied into app/src/main/res). */
const ANDROID_RES = 'android-res';

const SCREENSHOT_BASE = {
  target: 'google',
  group: 'screenshot',
  kind: 'image',
  formats: ['png', 'jpeg'],
  alpha: 'forbidden',
  localized: true,
  verified: true,
  sourceUrl: LISTING,
  maxTextShare: 0.2,
  discouragesFrames: true,
} as const;

function adaptiveLayer(layer: 'foreground' | 'background' | 'monochrome'): SpecEntry {
  return {
    id: `google.adaptive-icon.${layer}`,
    target: 'google',
    group: 'icon',
    folder: ANDROID_RES,
    name: `Adaptive launcher icon, ${layer} layer`,
    kind: 'image',
    required: false,
    condition: layer === 'monochrome' ? 'Needed for themed icons (Android 13+).' : 'Needed for the in-app launcher icon.',
    dimensions: { kind: 'fixed', sizes: squares(...ADAPTIVE_LAYER_SIDES), rotatable: false },
    formats: ['png'],
    alpha: layer === 'background' ? 'forbidden' : 'allowed',
    localized: false,
    verified: true,
    sourceUrl: ADAPTIVE,
    notes: '108 dp per density; the inner 66 dp are never clipped, keep the logo within 48–66 dp.',
  };
}

