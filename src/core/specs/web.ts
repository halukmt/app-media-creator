// Unverified values (third-party guides only) point to the research notes in this repo.
const RESEARCH = 'https://github.com/halukmt/app-media-creator/blob/dev/.claude/research/2026-11-18_store-media-specs.md';

const KB = 1024;
const MB = 1024 * KB;
const fixed = (...pairs: [number, number][]) => ({
  kind: 'fixed' as const,
  sizes: pairs.map(([width, height]): Size => ({ width, height })),
  rotatable: false,
});

/** Social profile and banner images. All sizes are from third-party guides, not from the networks' own docs. */
function social(id: string, name: string, size: [number, number], sourceUrl: string, notes?: string): SpecEntry {
  const formats: MediaFormat[] = ['png', 'jpeg'];
  return {
    id: `web.social.${id}`,
    target: 'web',
    group: 'social',
    name,
    kind: 'image',
    required: false,
    dimensions: fixed(size),
    formats,
    alpha: 'allowed',
    localized: false,
    verified: false,
    sourceUrl,
    ...(notes ? { notes } : {}),
  };
}

